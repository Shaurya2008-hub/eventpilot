import { BUDGET_CATEGORIES, type BudgetCategory } from "./budget";
import type { Plan } from "./schemas";

export const CATEGORY_DISPLAY_NAMES: Record<BudgetCategory, string> = {
  venue: "Venue & Hall",
  catering: "Catering & Food",
  decor: "Decor & Lighting",
  photography: "Photography & Video",
  entertainment: "Music & Entertainment",
  contingency: "Emergency Contingency",
};

/**
 * Builds the standard export filename for a celebration plan:
 * e.g., "wedding-2026-12-31.txt"
 */
export function buildPlanExportFilename(plan: Plan): string {
  const occasion = (plan?.input?.occasion || "celebration")
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9_-]+/g, "-");
  const date = (plan?.input?.eventDate || "undated").trim();
  return `${occasion}-${date}.txt`;
}

/**
 * Pure function that generates a well-structured plain-text summary of a Plan.
 * Includes: occasion, date, city, guests, budget total, category breakdown,
 * task timeline with dates and status, vendor checklist, theme ideas, and notes.
 *
 * Handles missing or optional fields gracefully.
 */
export function buildPlanText(plan: Plan): string {
  if (!plan) return "";

  const lines: string[] = [];
  const divider = "================================================================================";
  const subDivider = "--------------------------------------------------------------------------------";

  // Header
  lines.push(divider);
  lines.push("EVENTPILOT CELEBRATION PLAN");
  lines.push(divider);
  lines.push("");

  // Event Details
  const occasion = plan.input?.occasion
    ? plan.input.occasion.charAt(0).toUpperCase() + plan.input.occasion.slice(1)
    : "Celebration";
  const city = plan.input?.city || "Not specified";
  const eventDate = plan.input?.eventDate || "Not specified";
  const guests = plan.input?.guests ? plan.input.guests.toLocaleString("en-IN") : "0";
  const totalBudget = plan.input?.budget
    ? `₹${plan.input.budget.toLocaleString("en-IN")}`
    : "₹0";

  lines.push("EVENT DETAILS");
  lines.push(subDivider);
  lines.push(`Occasion: ${occasion}`);
  lines.push(`City: ${city}`);
  lines.push(`Event Date: ${eventDate}`);
  lines.push(`Guest Count: ${guests}`);
  lines.push(`Total Budget: ${totalBudget}`);

  if (plan.input?.atmosphere) {
    lines.push(`Atmosphere: ${plan.input.atmosphere}`);
  }
  if (plan.input?.dietary) {
    lines.push(`Dietary Notes: ${plan.input.dietary}`);
  }
  if (plan.input?.accessibilityNeeds) {
    lines.push(`Accessibility Needs: ${plan.input.accessibilityNeeds}`);
  }
  if (plan.input?.mustHaves && plan.input.mustHaves.length > 0) {
    lines.push(`Must-Haves: ${plan.input.mustHaves.join(", ")}`);
  }

  const sourceLabel =
    plan.source === "ai"
      ? `AI plan (${plan.modelUsed || "Gemini"})`
      : "Built-in planner";
  lines.push(`Plan Generated By: ${sourceLabel}`);
  lines.push("");

  // Budget Breakdown
  lines.push("BUDGET BREAKDOWN");
  lines.push(subDivider);
  const budgetTotalNum = plan.input?.budget || 0;
  if (plan.budget) {
    for (const cat of BUDGET_CATEGORIES) {
      const amount = plan.budget[cat] ?? 0;
      const pct =
        budgetTotalNum > 0 ? ((amount / budgetTotalNum) * 100).toFixed(1) : "0.0";
      const catName = CATEGORY_DISPLAY_NAMES[cat] || cat;
      lines.push(
        `${catName.padEnd(24)}: ₹${amount.toLocaleString("en-IN")} (${pct}%)`
      );
    }
  }
  lines.push(`Total Budget Allocation : ${totalBudget}`);
  lines.push("");

  // Timeline
  lines.push("PLANNING TIMELINE");
  lines.push(subDivider);
  const timeline = plan.timeline || [];
  if (timeline.length > 0) {
    const taskTitleMap = new Map(timeline.map((t) => [t.id, t.title]));

    timeline.forEach((task, idx) => {
      const statusLabel = task.status === "done" ? "[Completed]" : "[To-do]    ";
      const due = task.dueDate || "No date";
      let taskLine = `${String(idx + 1).padStart(2)}. ${statusLabel} ${due} - ${task.title}`;
      if (task.compressed) {
        taskLine += " (Compressed schedule)";
      }
      lines.push(taskLine);

      if (task.dependsOn && task.dependsOn.length > 0) {
        const depTitles = task.dependsOn
          .map((id) => taskTitleMap.get(id) || id)
          .join(", ");
        lines.push(`       Depends on: ${depTitles}`);
      }
    });
  } else {
    lines.push("No timeline tasks scheduled.");
  }
  lines.push("");

  // Vendor Checklist
  lines.push("VENDOR CHECKLIST");
  lines.push(subDivider);
  const checklist = plan.vendorChecklist || [];
  if (checklist.length > 0) {
    checklist.forEach((group) => {
      const vendorName =
        group.vendor.charAt(0).toUpperCase() + group.vendor.slice(1);
      lines.push(`${vendorName} Checklist:`);
      if (group.items && group.items.length > 0) {
        group.items.forEach((item) => {
          const mark = item.done ? "[X]" : "[ ]";
          lines.push(`  ${mark} ${item.label}`);
        });
      } else {
        lines.push("  (No checklist items)");
      }
      lines.push("");
    });
  } else {
    lines.push("No vendor checklist available.");
    lines.push("");
  }

  // Theme Ideas
  lines.push("THEME IDEAS");
  lines.push(subDivider);
  const ideas = plan.ideas || [];
  if (ideas.length > 0) {
    ideas.forEach((idea, idx) => {
      lines.push(`${idx + 1}. ${idea}`);
    });
  } else {
    lines.push("No theme ideas recorded.");
  }
  lines.push("");

  // Celebration Notes
  lines.push("CELEBRATION NOTES");
  lines.push(subDivider);
  const notes = plan.notes || [];
  if (notes.length > 0) {
    notes.forEach((note) => {
      lines.push(`- ${note}`);
    });
  } else {
    lines.push("No notes recorded.");
  }
  lines.push("");

  lines.push(divider);
  lines.push("Generated by EventPilot — AI Celebration Planner for Indian Families");
  lines.push(divider);

  return lines.join("\n");
}

/**
 * Triggers a client-side download of the plan as a .txt file.
 */
export function downloadPlanAsText(plan: Plan): void {
  if (typeof window === "undefined" || !plan) return;

  const text = buildPlanText(plan);
  const filename = buildPlanExportFilename(plan);
  const blob = new Blob([text], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);

  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
